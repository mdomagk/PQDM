#' Synthetic weekly 95th percentiles of H3, H5 and Plt
#'
#' Example data set with weekly 95th percentiles of 10-minute values of the
#' 3rd and 5th harmonic voltage (in % of the nominal voltage) and of the
#' long-term flicker severity Plt for 24 fictitious medium-voltage sites over
#' four years. The data are fully synthetic; no measured values were used.
#' Each series is the product of a level, a trend, an annual cycle, noise
#' and, for some series, event weeks. The types of course and
#' the ranges of their parameters were set by hand to resemble long-term
#' measurements. Each measurement (site and parameter) follows one type:
#'
#' | Type          | Measurements    | Trend (per year) | Season |
#' |---------------|-----------------|------------------|--------|
#' | flat          | 17 H3, 9 H5, 5 Plt | none          | at most +/-4 % |
#' | summer        | 7 H5, 4 Plt     | none             | +/-20 to 30 %, maximum week 27 |
#' | winter        | 3 H5            | none             | +/-20 to 30 %, maximum week 2 |
#' | rising        | 5 H3, 2 H5      | +10 to 14 %      | at most +/-4 % |
#' | falling       | 2 H3            | -12 to -18 %     | at most +/-4 % |
#' | summer rising | 3 H5            | +10 to 14 %      | +/-20 to 30 %, maximum week 27 |
#' | spiky         | 15 Plt          | none             | none; 10 event weeks in four years |
#'
#' The phases differ by a static unbalance and noise of their own; half of
#' the sites have an outage of the instrument (`NA`). The assignment of
#' the types to the sites is given in the script that generates the data.
#'
#' @format A tibble with 44928 rows and 6 columns:
#' \describe{
#'   \item{site}{Site identifier, `"S01"` to `"S24"`.}
#'   \item{voltage}{Nominal voltage, `"10 kV"` or `"20 kV"`.}
#'   \item{week}{Start of the week (Monday), class `Date`.}
#'   \item{phase}{Phase, `"L1"`, `"L2"` or `"L3"`.}
#'   \item{param}{Parameter, `"H3"`, `"H5"` or `"Plt"`.}
#'   \item{value}{Weekly 95th percentile, in % of the nominal voltage for
#'     `H3` and `H5`; `NA` for outages.}
#' }
#' @source Generated by `data-raw/make_pq_weekly_example.R`.
